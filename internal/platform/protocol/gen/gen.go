// gen 从 Go protocol 包的 structs 自动生成 TypeScript interface（web/src/platform/protocol.ts），
// 避免消息类型 + payload 手写镜像漂移（见技术设计 R-7）。
// 多游戏平台：默认扫描平台协议（platform/protocol）与各游戏私有协议（games/*/msg），
// 仍输出单文件，按来源分节注释。
//
// 用法: go run ./internal/platform/protocol/gen [-src "internal/platform/protocol,internal/games/*/msg"] [-out web/src/platform/protocol.ts]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

type field struct {
	Name      string // json 字段名
	TS        string // TS 类型
	Optional  bool   // omitempty
	Comment   string
	GoComment string
}

type iface struct {
	Name   string
	GoDoc  string
	Fields []field
}

type msgConst struct {
	GoName  string
	Value   string
	Comment string
}

// section 一个协议来源目录（平台或单个游戏）的扫描结果
type section struct {
	Title  string // 分节标题（如 "平台" / "游戏: ddz"）
	Ifaces []iface
	Consts []msgConst
}

func main() {
	src := flag.String("src", "internal/platform/protocol,internal/games/*/msg", "协议源码目录（逗号分隔，支持 glob）")
	out := flag.String("out", "web/src/platform/protocol.ts", "输出 TS 文件路径")
	flag.Parse()

	var dirs []string
	for _, part := range strings.Split(*src, ",") {
		part = strings.TrimSpace(part)
		if part == "" {
			continue
		}
		if strings.ContainsAny(part, "*?[") {
			matched, err := filepath.Glob(part)
			if err != nil {
				fatalf("匹配 %s 失败: %v", part, err)
			}
			dirs = append(dirs, matched...)
		} else {
			dirs = append(dirs, part)
		}
	}
	if len(dirs) == 0 {
		fatalf("未找到协议源码目录: %s", *src)
	}

	var sections []section
	for _, dir := range dirs {
		s, err := scanDir(dir)
		if err != nil {
			fatalf("扫描 %s 失败: %v", dir, err)
		}
		sections = append(sections, *s)
	}

	// MsgTypes 全局唯一对象：各分节常量合并（平台在前），接口按名称排序去重前缀分节输出。
	named := make(map[string]bool)
	var allIfaces []iface
	for _, s := range sections {
		for _, it := range s.Ifaces {
			if named[it.Name] {
				continue // 同名以先扫描的来源（平台）为准
			}
			named[it.Name] = true
			allIfaces = append(allIfaces, it)
		}
	}
	sort.Slice(allIfaces, func(i, j int) bool { return allIfaces[i].Name < allIfaces[j].Name })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by go run ./internal/platform/protocol/gen. DO NOT EDIT.\n\n")

	buf.WriteString("export interface Message<T = unknown> {\n  type: MessageType;\n  payload?: T;\n}\n\n")

	buf.WriteString("export const MsgTypes = {\n")
	for _, s := range sections {
		if len(s.Consts) == 0 {
			continue
		}
		fmt.Fprintf(&buf, "  // ── %s ──\n", s.Title)
		for _, c := range s.Consts {
			if c.Comment != "" {
				fmt.Fprintf(&buf, "  /** %s */\n", c.Comment)
			}
			fmt.Fprintf(&buf, "  %s: '%s',\n", c.GoName, c.Value)
		}
	}
	buf.WriteString("} as const;\n\n")
	buf.WriteString("export type MessageType = (typeof MsgTypes)[keyof typeof MsgTypes];\n\n")

	for _, it := range allIfaces {
		if it.Name == "Message" {
			continue
		}
		if it.GoDoc != "" {
			fmt.Fprintf(&buf, "/** %s */\n", it.GoDoc)
		}
		fmt.Fprintf(&buf, "export interface %s {\n", it.Name)
		for _, f := range it.Fields {
			if f.GoComment != "" {
				fmt.Fprintf(&buf, "  /** %s */\n", f.GoComment)
			}
			opt := ""
			if f.Optional {
				opt = "?"
			}
			fmt.Fprintf(&buf, "  %s%s: %s;\n", f.Name, opt, f.TS)
		}
		buf.WriteString("}\n\n")
	}

	if dir := filepath.Dir(*out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fatalf("创建输出目录失败: %v", err)
		}
	}
	if err := os.WriteFile(*out, buf.Bytes(), 0o644); err != nil {
		fatalf("写入 %s 失败: %v", *out, err)
	}
	constCount := 0
	for _, s := range sections {
		constCount += len(s.Consts)
	}
	fmt.Printf("✅ 已生成 %s（%d 个消息类型, %d 个 interface, %d 个分节）\n", *out, constCount, len(allIfaces), len(sections))
}

// scanDir 扫描单个协议目录的消息常量与 payload 结构
func scanDir(dir string) (*section, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		// 只解析协议定义文件，跳过测试与生成器
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		return nil, err
	}

	s := &section{Title: "平台"}
	if strings.HasPrefix(filepath.ToSlash(dir), "internal/games/") {
		s.Title = "游戏: " + strings.Split(strings.TrimPrefix(filepath.ToSlash(dir), "internal/games/"), "/")[0]
	}

	for _, pkg := range pkgs {
		for _, file := range pkg.Files {
			for _, decl := range file.Decls {
				gd, ok := decl.(*ast.GenDecl)
				if !ok {
					continue
				}
				for _, spec := range gd.Specs {
					switch sp := spec.(type) {
					case *ast.TypeSpec:
						st, ok := sp.Type.(*ast.StructType)
						if !ok {
							continue
						}
						s.Ifaces = append(s.Ifaces, iface{
							Name:   sp.Name.Name,
							GoDoc:  docText(gd.Doc),
							Fields: parseFields(st),
						})
					case *ast.ValueSpec:
						// MessageType 常量
						if isMessageType(sp.Type) {
							for i, name := range sp.Names {
								v := ""
								if i < len(sp.Values) {
									if lit, ok := sp.Values[i].(*ast.BasicLit); ok {
										v = strings.Trim(lit.Value, `"`)
									}
								}
								s.Consts = append(s.Consts, msgConst{
									GoName:  name.Name,
									Value:   v,
									Comment: inlineComment(sp.Comment),
								})
							}
						}
					}
				}
			}
		}
	}
	return s, nil
}

func parseFields(st *ast.StructType) []field {
	var out []field
	for _, f := range st.Fields.List {
		tsType := exprToTS(f.Type)
		jsonName := ""
		optional := false
		if f.Tag != nil {
			tag := reflect.StructTag(strings.Trim(f.Tag.Value, "`"))
			jt := tag.Get("json")
			if jt == "-" {
				continue
			}
			parts := strings.Split(jt, ",")
			jsonName = parts[0]
			for _, o := range parts[1:] {
				if o == "omitempty" {
					optional = true
				}
			}
		}
		if jsonName == "" && len(f.Names) > 0 {
			jsonName = f.Names[0].Name
		}
		if jsonName == "" {
			continue
		}
		out = append(out, field{
			Name:      jsonName,
			TS:        tsType,
			Optional:  optional,
			GoComment: inlineComment(f.Comment),
		})
	}
	return out
}

// exprToTS 将 Go 类型表达式映射为 TS 类型
func exprToTS(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int32", "int64", "float32", "float64":
			return "number"
		default:
			return t.Name // 协议包内 struct 引用
		}
	case *ast.ArrayType:
		return exprToTS(t.Elt) + "[]"
	case *ast.StarExpr:
		return exprToTS(t.X) + " | null"
	case *ast.SelectorExpr:
		if t.Sel.Name == "RawMessage" {
			return "unknown"
		}
		return t.Sel.Name
	default:
		return "unknown"
	}
}

// isMessageType 判断常量类型是否为 MessageType（含游戏包内的 protocol.MessageType 限定写法）
func isMessageType(e ast.Expr) bool {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name == "MessageType"
	case *ast.SelectorExpr:
		return t.Sel.Name == "MessageType"
	}
	return false
}

func docText(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	var parts []string
	for _, c := range cg.List {
		parts = append(parts, strings.TrimSpace(strings.TrimPrefix(c.Text, "//")))
	}
	return strings.Join(parts, " ")
}

func inlineComment(cg *ast.CommentGroup) string {
	if cg == nil {
		return ""
	}
	return strings.TrimSpace(strings.TrimPrefix(cg.List[0].Text, "//"))
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-protocol: "+format+"\n", args...)
	os.Exit(1)
}
