// GetPositionBonus 获取指定棋子在指定位置的加成值
func GetPositionBonus(piece, row, col, myCamp int) int {
	t := rule.TypeOf(piece)
	camp := rule.CampOf(piece)

	// 如果是黑方，镜像翻转到红方视角
	if camp == rule.CampBlack {
		row = 9 - row
	}

	switch t {
	case 2: // 车
		return rookPositionTable[row][col]
	case 3: // 马
		return knightPositionTable[row][col]
	case 4: // 炮
		return cannonPositionTable[row][col]
	case 5: // 相/象
		return elephantPositionTable[row][col]
	case 6: // 仕/士
		return advisorPositionTable[row][col]
	case 7: // 兵/卒
		if camp == rule.CampRed {
			return pawnPositionRed[row][col]
		} else {
			// 黑卒镜像（已在函数开头翻转）
			return pawnPositionRed[row][col]
		}
	default:
		return 0
	}
}
