// OpeningEntry 开局库条目：着法 + 流行度权重（P3 统计权重）
type OpeningEntry struct {
	Move   rule.Move
	Weight int // 流行度/权重（越高越常见）
}

// ChessOpeningBook 中国象棋开局库（加权版，P3 扩充至 100+ 定式）
//
// key 为「完整局面 90 格 + 执子方」的精确编码：只有构建记录时生成的局面才会命中，
// 中盘不可能误命中开局着法。
type ChessOpeningBook struct {
	mu      sync.RWMutex
	entries map[string][]OpeningEntry
}

var globalChessOpeningBook = newChessOpeningBook()

// newChessOpeningBook 构建开局库并从预定义开局线路填充
func newChessOpeningBook() *ChessOpeningBook {
	book := &ChessOpeningBook{entries: make(map[string][]OpeningEntry)}
	book.buildFromLines()
	return book
}

// openingLine 开局线路：一系列着法 + 线路权重
type openingLine struct {
	moves  []rule.Move
	weight int // 线路流行度（累加到沿途每个局面的对应着法上）
}

// mv 辅助：紧凑创建着法
func mv(fr, fc, tr, tc int) rule.Move {
	return rule.Move{FromRow: fr, FromCol: fc, ToRow: tr, ToCol: tc}
}

// buildFromLines 从预定义开局线路构建开局库。
// 对每条线路，从初始局面开始逐步走子，沿途每个局面的下一步着法
// 以线路权重累加到 entries 中（同一局面多条线路经过时权重叠加）。
// 防御：线路若含非法着法则丢弃该步及其后续所有条目（非法着法若被注册，
// 精确局面命中时会被引擎直接执行，产生非法走子）；数据正确性由
// TestOpeningBookLinesLegal 回归测试保障，此处兜底保证坏数据不进库。
func (cob *ChessOpeningBook) buildFromLines() {
	for _, line := range openingLines {
		board := rule.NewBoard()
		camp := rule.CampRed
		for _, m := range line.moves {
			if !isLegalBookMove(board, camp, m) {
				break
			}
			key := positionKey(board, camp)
			cob.addEntry(key, m, line.weight)
			rule.ApplyMove(board, m)
			camp = rule.CampRed + rule.CampBlack - camp
		}
	}
}

// isLegalBookMove 判断着法是否为当前局面的合法走子
func isLegalBookMove(board []int, camp int, m rule.Move) bool {
	for _, lm := range rule.AllLegalMoves(board, camp) {
		if lm == m {
			return true
		}
	}
	return false
}

// addEntry 添加一条开局记录（初始化阶段调用，无锁）
func (cob *ChessOpeningBook) addEntry(key string, move rule.Move, weight int) {
	cob.entries[key] = append(cob.entries[key], OpeningEntry{Move: move, Weight: weight})
}

// Lookup 查找开局库：命中则按流行度权重随机返回一条着法
func (cob *ChessOpeningBook) Lookup(board []int, camp int) (rule.Move, bool) {
	key := positionKey(board, camp)
	cob.mu.RLock()
	entries, ok := cob.entries[key]
	cob.mu.RUnlock()
	if !ok || len(entries) == 0 {
		return rule.Move{}, false
	}

	// 按权重加权随机选择
	total := 0
	for _, e := range entries {
		total += e.Weight
	}
	pick := rand.IntN(total)
	for _, e := range entries {
		pick -= e.Weight
		if pick < 0 {
			return e.Move, true
		}
	}
	return entries[0].Move, true
}

// positionKey 精确局面键：90 格棋子编码 + 执子方，逐字节拼接
func positionKey(board []int, camp int) string {
	var sb strings.Builder
	sb.Grow(rule.Rows*rule.Cols + 1)
	for _, p := range board {
		sb.WriteByte(byte(p))
	}
	sb.WriteByte(byte(camp))
	return sb.String()
}

